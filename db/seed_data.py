def seed_all(conn):
    from datetime import date
    today = date.today().isoformat()

    if conn.execute("SELECT COUNT(*) c FROM deputies_structure").fetchone()["c"] == 0:
        for d in DEPUTIES:
            conn.execute("INSERT OR IGNORE INTO deputies_structure (deputy) VALUES (?)", (d,))

    if conn.execute("SELECT COUNT(*) c FROM centers_structure").fetchone()["c"] == 0:
        for row in CENTERS:
            center_name, canonical, supply, deputy, quota = row
            conn.execute("""
                INSERT OR IGNORE INTO centers_structure
                    (center_name, canonical_name, supply_type, deputy, monthly_quota)
                VALUES (?,?,?,?,?)
            """, (center_name, canonical, supply, deputy, quota))

    if conn.execute("SELECT COUNT(*) c FROM pricing_rules").fetchone()["c"] == 0:
        for row in PRICING_RULES:
            deputy, article, category, amount = row
            conn.execute("""
                INSERT INTO pricing_rules
                    (deputy, legal_article, category, amount, valid_from, created_by)
                VALUES (?,?,?,?,?,?)
            """, (deputy, article, category, amount, today, "seed"))

    if conn.execute("SELECT COUNT(*) c FROM specialists_equipment_bonus").fetchone()["c"] == 0:
        for center_name, canonical, supply, deputy, quota in CENTERS:
            conn.execute("""
                INSERT OR IGNORE INTO specialists_equipment_bonus
                    (center_name, supply_type, specialists, equipment, bonus)
                VALUES (?,?,0,0,0)
            """, (center_name, supply or ''))

    conn.commit()